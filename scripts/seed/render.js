// Converts finished row objects (already-typed JS values) into SQL text.
// This is the only place that turns a JS value into a SQL literal -- every
// generated string coming from the AI passes through sqlString() here
// before it ever touches the .sql file. Nothing is ever string-templated
// into a query directly.

const ROWS_PER_INSERT = 100

// Rejects NUL (Postgres text can never store it -- better to fail loudly
// here than let COPY/INSERT fail later with a confusing error) and escapes
// both the quote and the backslash unconditionally by using PostgreSQL's
// E'' escape-string syntax. This does not depend on the server's
// standard_conforming_strings setting either way, unlike plain ''
// literals combined with raw backslashes would.
export function sqlString(value) {
  const s = String(value)
  if (s.indexOf(String.fromCharCode(0)) !== -1) {
    throw new Error('refusing to render a string containing a NUL byte')
  }
  const escaped = s.replace(/\\/g, '\\\\').replace(/'/g, "''")
  return `E'${escaped}'`
}

export function sqlLiteral(value) {
  if (value === null || value === undefined) return 'NULL'
  if (value instanceof Date) return sqlString(value.toISOString())
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`refusing to render non-finite number: ${value}`)
    return String(value)
  }
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE'
  if (typeof value === 'object' && value.__raw) return value.value
  if (Array.isArray(value) || (typeof value === 'object' && value.__jsonb)) {
    const payload = value.__jsonb ? value.value : value
    return `${sqlString(JSON.stringify(payload))}::jsonb`
  }
  if (typeof value === 'string') return sqlString(value)
  throw new Error(`don't know how to render value of type ${typeof value}`)
}

// Wraps a plain JS value/array so sqlLiteral() renders it as a ::jsonb
// literal instead of a plain string.
export function jsonb(value) {
  return { __jsonb: true, value }
}

// Wraps a raw SQL fragment so sqlLiteral() renders it verbatim — used for
// now()-relative timestamps that must survive the deterministic seed pipeline.
export function raw(sql) {
  return { __raw: true, value: sql }
}

// Renders one or more `INSERT INTO table (cols) VALUES (...), (...);`
// statements for `rows`, split into blocks of ROWS_PER_INSERT so no single
// statement gets unreasonably large. `rows` is an array of arrays, values
// in the same order as `columns`.
export function renderInsert(table, columns, rows) {
  if (rows.length === 0) return ''
  const statements = []
  for (let i = 0; i < rows.length; i += ROWS_PER_INSERT) {
    const chunk = rows.slice(i, i + ROWS_PER_INSERT)
    const valuesSql = chunk
      .map((row) => `  (${row.map(sqlLiteral).join(', ')})`)
      .join(',\n')
    statements.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${valuesSql};`)
  }
  return statements.join('\n\n')
}

// Assembles the complete seed file: BEGIN, the fixed TRUNCATE list (never
// users/user_roles/invite_codes -- S3), every table's inserts in FK-safe
// order, COMMIT.
export function renderSeedFile(inserts) {
  const header = `-- Generated by scripts/generate-seed.js. Do not hand-edit -- re-run the
-- generator instead; any manual change here is lost on the next run.
--
-- Auth data is never touched. This file only ever writes to the market
-- tables listed in the TRUNCATE below (drivers and their 039 driver_qualification
-- files, trucks, loads and their children).
BEGIN;

TRUNCATE TABLE truck_daily_metrics, maintenance_records, load_postings, loads, driver_qualification, trucks, drivers CASCADE;
`
  const body = inserts.filter(Boolean).join('\n\n')
  const footer = '\nCOMMIT;\n'
  return `${header}\n${body}\n${footer}`
}
